_SPRITES = {
    ("egg",       "idle"):     EGG_IDLE,
    ("hatchling", "idle"):     HATCHLING_IDLE,
    ("hatchling", "happy"):    HATCHLING_HAPPY,
    ("hatchling", "hungry"):   HATCHLING_HUNGRY,
    ("hatchling", "sad"):      HATCHLING_IDLE,    # fallback to idle
    ("hatchling", "sleeping"): HATCHLING_SLEEPING,
    ("drake",     "idle"):     DRAKE_IDLE,
    ("drake",     "happy"):    DRAKE_HAPPY,
    ("drake",     "hungry"):   DRAKE_HUNGRY,
    ("drake",     "sad"):      DRAKE_SAD,
    ("drake",     "sleeping"): DRAKE_SLEEPING,
    ("dragon",    "idle"):     DRAGON_IDLE,
    ("dragon",    "happy"):    DRAGON_HAPPY,
    ("dragon",    "hungry"):   DRAGON_HUNGRY,
    ("dragon",    "sad"):      DRAGON_SAD,
    ("dragon",    "sleeping"): DRAGON_SLEEPING,
}


def get_sprite(stage, mood):
    key = (stage, mood)
    if key in _SPRITES:
        return _SPRITES[key]
    # fallback: same stage, idle
    fallback = (stage, "idle")
    if fallback in _SPRITES:
        return _SPRITES[fallback]
    return EGG_IDLE


def render_sprite(sprite, frame_idx):
    """Return one rich.text.Text per sprite row (no trailing newlines)."""
    frame = sprite.frames[frame_idx % len(sprite.frames)]
    rows = []
    for row in frame:
        t = Text()
        for cell in row:
            if cell == 0:
                t.append("  ")
            else:
                t.append("██", style=sprite.palette[cell])
        rows.append(t)
    return rows
